"""Embed the static controller in flash. No credentials are copied into assets."""
from pathlib import Path
root=Path(__file__).resolve().parent
target=root.parent/'firmware'/'rover_wifi_control'/'WebAssets.h'
assets={'INDEX_HTML':'index.html','STYLE_CSS':'style.css','APP_JS':'app.mjs',
        'CONTROLS_JS':'controls.mjs','WIFI_LINK_JS':'wifi-link.mjs'}
parts=['// Generated by rover_control/build_wifi_assets.py.\n#pragma once\n#include <Arduino.h>\n']
for name,file in assets.items():
    content=(root/file).read_text()
    assert ')ROVER_ASSET"' not in content
    parts.append(f'const char {name}[] PROGMEM = R"ROVER_ASSET({content})ROVER_ASSET";\n')
target.write_text(''.join(parts))
print(f'Embedded {len(assets)} web files ({target.stat().st_size} bytes) into ESP32 assets.')
